"""
Lesson 05 · 提示词工程（Prompt Engineering）—— 不训练模型也能"调教"它
======================================================================

本课要回答的问题：
  1. 想让模型稳定输出"我要的格式/内容"，不微调模型，怎么办？
  2. 几个最实用、立竿见影的技巧是什么？

运行方式：
  python lessons/lesson_05_prompt.py

核心心法：
  模型的行为 90% 由【你给的提示词】决定。它不会真的"听懂意图"，
  它是【照着文字模式往下接】。所以写提示词 = 把要求说得越具体、越像模板越好。

本课演示 4 个最常用技巧：
  A. 角色设定：给一个具体身份/语气，约束它的口吻
  B. 结构化输出：让模型输出 JSON，再用代码解析 —— 让 AI 能被程序"用起来"
  C. 给示例（few-shot）：举 1~2 个例子，它就会照葫芦画瓢
  D. 让它先思考（chain-of-thought）：难题先自己推理，再给结论
"""

import json

from config import MODEL, get_client

client = get_client()


def ask(messages: list, **extra) -> str:
    resp = client.chat.completions.create(model=MODEL, messages=messages, **extra)
    return resp.choices[0].message.content


# =====================================================================
# A. 角色设定：给一个身份，语气立刻改变
# =====================================================================
print("===== A. 角色设定的力量 =====")
no_role = ask([{"role": "user", "content": "我现在很焦虑，不知道明天面试怎么办。"}])
with_role = ask([
    {"role": "system",
     "content": "你是一个擅长鼓励人的资深生涯教练。说话温柔、具体、给可执行步骤，"
               "每次最多 3 条建议，每条不超过 20 字。"},
    {"role": "user", "content": "我现在很焦虑，不知道明天面试怎么办。"},
])
print("【无角色】", no_role, "\n")
print("【有角色】", with_role, "\n")


# =====================================================================
# B. 结构化输出：让模型输出 JSON，代码解析后用（企业应用核心）
# =====================================================================
print("===== B. 让模型输出 JSON（结构化输出）=====")
# 提示词要它输出 JSON 还不够保险，DeepSeek 还提供了"强制 JSON 模式"：
#   response_format={"type": "json_object"} —— 它保证输出一定能被 json.loads 解析。
#   注意：json 模式要求提示词里包含"json"字样（下面 system 已包含），否则会报错。
raw = ask(
    [
        {"role": "system",
         "content": "你只输出合法的 JSON，不要任何解释、不要代码块标记。\n"
                    "字段必须严格使用这些名字：name、time、party_size、preference。"},
        {"role": "user",
         "content": "把这句话拆成结构化信息：用户张三想预订明天晚上 7 点、2 人的靠窗座位。"},
    ],
    response_format={"type": "json_object"},
)
print("【模型原始返回】", raw)
# 💡 上面为什么要在 system 里明确字段名？—— 模型猜不到你心里的字段叫法。
#    不写清楚，它可能自创 intent/user/seat_preference 等字段，你的代码就取不到值。
#    这暴露了真实世界的铁律：和模型对接的结构，必须由你在提示词里"定义好"。

# 用代码解析它，验证真能被程序用起来
try:
    data = json.loads(raw)
    print("【解析后】姓名 =", data.get("name"),
          "| 时间 =", data.get("time"),
          "| 人数 =", data.get("party_size"),
          "| 偏好 =", data.get("preference"))
except json.JSONDecodeError:
    print("⚠️ 解析失败（模型没听话）。对策：在提示词里给一个输出样例，见下面 C。")


# =====================================================================
# C. 给示例（few-shot）：模型最擅长模仿你给的例子
# =====================================================================
print("\n===== C. few-shot：给个例子，它就会照着做 =====")
few_shot = ask([
    {"role": "system",
     "content": "把用户的评论按【正面/中性/负面】分类，并用这个格式回答：\n"
               "情感：(分类)\n理由：(一句话)"},
    # 👇 下面这组 user/assistant 就是"示例"，教模型输出的样子
    {"role": "user", "content": "这外卖包装真好看，分量也足！"},
    {"role": "assistant", "content": "情感：正面\n理由：夸了包装和分量。"},
    {"role": "user", "content": "等了一小时餐还没到，客服也没人理。"},
])
print(few_shot)


# =====================================================================
# D. 让它先思考（chain-of-thought）—— 数学难题正确率立涨
# =====================================================================
print("\n===== D. 让模型先思考再回答 =====")
easy = ask([
    {"role": "user", "content": "计算：12 ÷ 3 = ?（只回答数字）"},
])
hard = ask([
    {"role": "user",
     "content": "一个农场里鸡和兔子共 35 个头、94 只脚。请问各有多少只？"
               "请先分步推理，再给出最终结论。"},
])
print("【简单题直接答】", easy)
print("\n【复杂题 + 要求推理】\n", hard)

print("\n" + "=" * 55)
print("""小结 —— 四条最值钱的提示词经验：
  1. system 里把【身份 + 语气 + 约束】写全，模型立刻"变个人"。
  2. 要让程序处理结果，就让模型输出 JSON，并且给个输出样例。
  3. 想让模型学会一种新格式，就给 1~2 组例子（few-shot）。
  4. 遇到逻辑/数学题，明确要求"先分步思考再给结论"，准确率大幅提升。""")

